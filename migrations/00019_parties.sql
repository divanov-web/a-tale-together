-- Пункт 19: группы персонажей (docs/game/models/party.md). Идентификатор BY DEFAULT: движок создаёт группы при
-- разделении по идентификаторам, зарезервированным в снимке раунда (ReservePartyIDs), чтобы раунд был воспроизводим.
CREATE TABLE parties (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_id             bigint NOT NULL REFERENCES games (id) ON DELETE CASCADE,
    season_id           bigint NOT NULL REFERENCES seasons (id),
    name                text NOT NULL,
    status              text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'disbanded')),
    leader_character_id bigint REFERENCES characters (id) ON DELETE SET NULL,
    location_id         bigint REFERENCES locations (id) ON DELETE SET NULL,
    motto               text NOT NULL DEFAULT '',
    summary             text NOT NULL DEFAULT '',
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX parties_game_idx ON parties (game_id);
CREATE UNIQUE INDEX parties_season_name_idx ON parties (season_id, lower(name)) WHERE status = 'active';
ALTER TABLE characters ADD CONSTRAINT characters_party_fk FOREIGN KEY (party_id) REFERENCES parties (id) ON DELETE SET NULL;
CREATE INDEX characters_party_idx ON characters (party_id);

