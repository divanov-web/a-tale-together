-- Уже запущенные игры: все персонажи активного сезона собираются в группу по умолчанию, лидер — персонаж
-- администратора игры (иначе первый созданный), локация — его локация; черновики получат группу при /begin.
-- +goose StatementBegin
DO $$
DECLARE
    g RECORD;
    leader RECORD;
    pid bigint;
BEGIN
    FOR g IN SELECT games.id, games.created_by_user_id, seasons.id AS season_id
             FROM games JOIN seasons ON seasons.game_id = games.id AND seasons.status = 'active'
             WHERE games.status IN ('active', 'paused')
               AND EXISTS (SELECT 1 FROM characters c WHERE c.game_id = games.id AND c.season_id = seasons.id) LOOP
        SELECT c.id, c.location_id INTO leader FROM characters c
        WHERE c.game_id = g.id AND c.season_id = g.season_id
        ORDER BY (c.user_id = g.created_by_user_id) DESC, (c.status IN ('inactive', 'dead')), c.id
        LIMIT 1;
        INSERT INTO parties (game_id, season_id, name, status, leader_character_id, location_id)
        VALUES (g.id, g.season_id, 'Ночной дозор', 'active', leader.id, leader.location_id) RETURNING id INTO pid;
        UPDATE characters SET party_id = pid WHERE game_id = g.id AND season_id = g.season_id;
    END LOOP;
END $$;
-- +goose StatementEnd

